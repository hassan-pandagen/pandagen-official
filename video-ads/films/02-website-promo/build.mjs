// Writes the HyperFrames root for each export from one scene list.
//   index.html                      16:9 master (this folder is the main HyperFrames project)
//   formats/9x16/index.html         9:16 social
//   formats/1x1/index.html          1:1 square
//   formats/9x16-reduced/index.html 9:16, reduced motion
// HyperFrames allows one root per project, so each extra format is its own small project whose
// compositions/, assets/ and audio/ are symlinks back to this folder. Scenes read window.FILM.
// Usage: node build.mjs   (from this folder)
import { writeFileSync, mkdirSync, existsSync, symlinkSync, lstatSync, copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const DURATION = 43.2; // 18 bars at 100 BPM
// [id, file, start, duration]. Cuts land on bars (2.4 s): 4.8, 9.6, 19.2, 24.0, 28.8, 33.6, 38.4.
// Each scene starts 0.6 s before its cut (its entrance) and stays 0.4 s past the next cut (overlap).
export const SCENES = [
  ["s01", "s01-hook", 0, 5.2],
  ["s02", "s02-wall", 4.2, 5.8],
  ["s03", "s03-tour", 9.0, 10.6],
  ["s04", "s04-phone", 18.6, 5.8],
  ["s05", "s05-search", 23.4, 5.8],
  ["s06", "s06-automation", 28.2, 5.8],
  ["s07", "s07-founders", 33.0, 5.8],
  ["s08", "s08-end", 37.8, 5.4],
];
const FORMATS = [
  { dir: ".", format: "16x9", motion: "full", W: 1920, H: 1080, label: "16:9 master" },
  { dir: "formats/9x16", format: "9x16", motion: "full", W: 1080, H: 1920, label: "9:16 social" },
  { dir: "formats/1x1", format: "1x1", motion: "full", W: 1080, H: 1080, label: "1:1 square" },
  { dir: "formats/9x16-reduced", format: "9x16", motion: "reduced", W: 1080, H: 1920, label: "9:16 reduced motion" },
];
const FONTS = `
@font-face{font-family:Anton;font-weight:400;font-style:normal;src:url(assets/fonts/anton-latin.woff2) format("woff2")}
@font-face{font-family:Inter;font-weight:100 900;font-style:normal;src:url(assets/fonts/inter-latin.woff2) format("woff2")}
@font-face{font-family:"PT Serif";font-weight:400;font-style:normal;src:url(assets/fonts/pt-serif-normal-400-latin.woff2) format("woff2")}
@font-face{font-family:"PT Serif";font-weight:400;font-style:italic;src:url(assets/fonts/pt-serif-italic-400-latin.woff2) format("woff2")}
@font-face{font-family:"PT Serif";font-weight:700;font-style:normal;src:url(assets/fonts/pt-serif-normal-700-latin.woff2) format("woff2")}`;

const hasAudio = existsSync(join(HERE, "audio", "mix.wav"));

function root(f) {
  const hosts = SCENES.map(([id, file, start, dur], i) =>
    `  <div id="${id}-host" data-composition-id="${id}" data-composition-src="compositions/${file}.html" data-start="${start}" data-duration="${dur}" data-track-index="${1 + (i % 2)}"></div>`).join("\n");
  const audio = hasAudio ? `\n  <audio id="music" src="audio/mix.wav" data-start="0" data-duration="${DURATION}" data-track-index="4" data-volume="1"></audio>` : "";
  return `<!doctype html>
<html lang="en" class="f${f.format} m-${f.motion}">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=${f.W}, height=${f.H}" />
<title>PandaCodeGen website promo · ${f.label}</title>
<!-- Generated by build.mjs. Edit the scene list there and the scenes in compositions/. -->
<script>window.FILM = { format: "${f.format}", motion: "${f.motion}" };</script>
<script src="assets/vendor/gsap.min.js"></script>
<script src="assets/kit.js"></script>
<link rel="stylesheet" href="assets/film.css" />
<style>${FONTS}
html, body { width: ${f.W}px; height: ${f.H}px; }
</style>
</head>
<body>
<div id="main" data-composition-id="main" data-start="0" data-duration="${DURATION}" data-width="${f.W}" data-height="${f.H}">
  <div id="s00-host" data-composition-id="s00" data-composition-src="compositions/s00-ground.html" data-start="0" data-duration="${DURATION}" data-track-index="0"></div>
${hosts}${audio}
</div>
<script>
  window.__timelines["main"] = gsap.timeline({ paused: true });
</script>
</body>
</html>
`;
}

for (const f of FORMATS) {
  const dir = join(HERE, f.dir);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "index.html"), root(f));
  if (f.dir !== ".") {
    for (const sub of ["compositions", "assets", "audio"]) {
      const p = join(dir, sub);
      if (!existsSync(p) && !(() => { try { return lstatSync(p).isSymbolicLink(); } catch { return false; } })()) symlinkSync(join("..", "..", sub), p);
    }
    copyFileSync(join(HERE, "hyperframes.json"), join(dir, "hyperframes.json"));
  }
  console.log("wrote", join(f.dir, "index.html"));
}
